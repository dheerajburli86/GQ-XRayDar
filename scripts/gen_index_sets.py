# One-off generator: reads the owner's workbook (New_Index_Creation.xlsx) and writes
# engine/reference/indexSetsData.js. Run: python3 scripts/gen_index_sets.py <xlsx>
import sys, json, openpyxl
wb = openpyxl.load_workbook(sys.argv[1], data_only=True)
def sets(ws, country_col=False):
    out, order, country = {}, [], {}
    for r in ws.iter_rows(values_only=True):
        a = (r[0] or "").strip() if isinstance(r[0], str) else r[0]
        b = (r[1] or "").strip() if isinstance(r[1], str) else r[1]
        if not a or not b or a.lower() == "index": continue
        if a not in out: out[a] = []; order.append(a)
        out[a].append(b)
        if country_col and len(r) > 2 and r[2]: country[b] = str(r[2]).strip()
    return [{"code": k, "members": out[k]} for k in order], country
s1, c1 = sets(next(w for w in wb if w.title.strip()=="Exchange Major Indices"), True)
s2, _ = sets(next(w for w in wb if w.title.strip()=="US ETF Indices"))
js = "// Generated by scripts/gen_index_sets.py from New_Index_Creation.xlsx. Do not edit by hand.\n"
js += "export const EXCHANGE_SETS = " + json.dumps(s1, indent=1) + ";\n"
js += "export const EXCHANGE_COUNTRY = " + json.dumps(c1, indent=1) + ";\n"
js += "export const ETF_SETS = " + json.dumps(s2, indent=1) + ";\n"
open("engine/reference/indexSetsData.js", "w").write(js)
print(len(s1), "exchange sets,", len(s2), "ETF sets")
